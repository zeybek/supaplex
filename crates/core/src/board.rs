//! The game's per-cell memory, laid out as the game lays it out.
//!
//! In the game's data segment the level is 1536 words (one per byte of a
//! level file, so the 96 bytes of level settings after the field sit in
//! "cells" 1440..1535 as tiles), and right after it come 1536 signed
//! explosion timers, one byte per cell. Code that looks past the field's
//! edge reads and writes this neighbouring memory, so it is kept here as
//! well: the timers after the level, and the six rows of "cells" before it.
//! Those rows hold zeros, the "LEVELS.DAT" file name, a key table, the
//! keyboard state, the tables of object routines and some of the game's
//! own counters; the counters that matter to play live in this memory
//! (see [`Var`]) so that whatever lands on them changes them, as in the
//! game. Anything further away reads as zero and is never written.

use crate::LEVEL_BYTES;

/// The data-segment offset this memory starts at; the level starts at
/// 0x1834, six rows of 60 words later.
const DS_BASE: u16 = 0x1564;
const LEVEL_AT: i32 = 0x1834 - DS_BASE as i32;
const TIMERS: i32 = LEVEL_AT + 2 * LEVEL_BYTES as i32;
const SIZE: usize = TIMERS as usize + LEVEL_BYTES;

pub const W: i32 = 60;

/// The object pass covers cell 61 (row 1, column 1) to cell 1378 (row 22,
/// column 58).
pub const SCAN_FIRST: i32 = 61;
pub const SCAN_LEN: usize = 1318;

/// The game's counters that sit in the rows before the level, by their
/// data-segment offsets.
#[derive(Clone, Copy)]
pub enum Var {
    /// Infotrons still needed (byte).
    InfotronsLeft = 0x164a,
    /// The same, as shown on the panel (byte).
    InfotronsShown = 0x164b,
    /// Red disks Murphy carries (byte).
    RedDisks = 0x164c,
    /// Frames played (word).
    Tick = 0x164d,
    /// Mask for the terminals' random blink delay (byte).
    TerminalMask = 0x165a,
    /// A terminal has been used (byte).
    TerminalUsed = 0x165b,
    /// 1: leave the level at the end of this frame (word).
    Leave = 0x1664,
    /// Frames left before leaving the level (word).
    Quit = 0x1668,
    /// Nonzero: leave the level before counting the frame (word).
    Halt = 0x166a,
}

