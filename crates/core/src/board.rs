#[derive(Clone)]
pub struct Board {
    mem: [u8; SIZE],
}

impl Board {
    pub const fn new() -> Board {
        Board { mem: [0; SIZE] }
    }

    /// Empty level and timers, the rows before them as at a level start.
    pub fn reset(&mut self) {
        self.mem = [0; SIZE];
        self.mem[..BEFORE_LEVEL.len()].copy_from_slice(&BEFORE_LEVEL);
        // Values the game has put there by then: the keyboard interrupt
        // vector it replaced (the PC BIOS one, F000:E987), and the flag it
        // sets before every level.
        for (at, value) in [
            (0x16ed, 0x87),
            (0x16ee, 0xe9),
            (0x16ef, 0x00),
            (0x16f0, 0xf0),
            (0x17ae, 1),
        ] {
            self.poke(at - DS_BASE as i32, value);
        }
    }

    // Memory past either end reads as 0 and takes no writes. `get` rather
    // than indexing leaves no panic in the module.
    fn peek(&self, at: i32) -> u8 {
        usize::try_from(at)
            .ok()
            .and_then(|i| self.mem.get(i))
            .copied()
            .unwrap_or(0)
    }

    fn poke(&mut self, at: i32, value: u8) {
        if let Some(byte) = usize::try_from(at).ok().and_then(|i| self.mem.get_mut(i)) {
            *byte = value;
        }
    }

    pub fn tile(&self, cell: i32) -> u8 {
        self.peek(LEVEL_AT + 2 * cell)
    }

    pub fn state(&self, cell: i32) -> u8 {
        self.peek(LEVEL_AT + 2 * cell + 1)
    }

    /// Tile in the low byte, state in the high byte.
    pub fn word(&self, cell: i32) -> u16 {
        self.tile(cell) as u16 | (self.state(cell) as u16) << 8
    }

    pub fn set_tile(&mut self, cell: i32, tile: u8) {
        self.poke(LEVEL_AT + 2 * cell, tile);
    }

    pub fn set_state(&mut self, cell: i32, state: u8) {
        self.poke(LEVEL_AT + 2 * cell + 1, state);
    }

    pub fn set(&mut self, cell: i32, word: u16) {
        self.set_tile(cell, word as u8);
        self.set_state(cell, (word >> 8) as u8);
    }

    pub fn timer(&self, cell: i32) -> i8 {
        self.peek(TIMERS + cell) as i8
    }

    pub fn set_timer(&mut self, cell: i32, value: i8) {
        self.poke(TIMERS + cell, value as u8);
    }

    fn var_at(var: Var) -> i32 {
        var as i32 - DS_BASE as i32
    }

    pub fn byte(&self, var: Var) -> u8 {
        self.peek(Self::var_at(var))
    }

    pub fn set_byte(&mut self, var: Var, value: u8) {
        self.poke(Self::var_at(var), value);
    }

    pub fn word_var(&self, var: Var) -> u16 {
        let at = Self::var_at(var);
        self.peek(at) as u16 | (self.peek(at + 1) as u16) << 8
    }

    pub fn set_word_var(&mut self, var: Var, value: u16) {
        let at = Self::var_at(var);
        self.poke(at, value as u8);
        self.poke(at + 1, (value >> 8) as u8);
    }
}
